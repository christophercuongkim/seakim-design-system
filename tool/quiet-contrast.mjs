// Contrast table for CHR-190: alpha hairlines, ink primary, and each app hue's
// link/focus colour on every surface, both themes. Same maths as the
// conformance contrast gate (tool/oklch.mjs).
// Usage: node tool/quiet-contrast.mjs > docs/research/quiet-contrast.md
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { oklchToRgb, contrast } from './oklch.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const strip = f => readFileSync(join(ROOT, f), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

function cssDecls(src) {
  const out = {};
  for (const m of src.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
    for (const d of m[2].matchAll(/(--[\w-]+)\s*:\s*([^;]+)/g)) out[d[1]] = d[2].trim();
  }
  return out;
}
function toRgb(name, map, depth = 0) {
  const v = map[name]?.trim();
  if (!v || depth > 8) return null;
  const ref = v.match(/^var\(\s*(--[\w-]+)/);
  if (ref) return toRgb(ref[1], map, depth + 1);
  const hx = v.match(/^#([0-9a-fA-F]{6})$/);
  if (hx) return [0, 2, 4].map(i => parseInt(hx[1].slice(i, i + 2), 16));
  const ok = v.match(/^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)/);
  if (ok) return oklchToRgb(+ok[1], +ok[2], +ok[3]);
  return null; // color-mix() etc.
}

const base = cssDecls(strip('tokens/colors.css'));
const light = cssDecls(strip('tokens/theme-light.css'));
const apps = {};
for (const m of strip('tokens/apps.css').matchAll(/\[data-app="(\w+)"\][^{]*\{([^}]*)\}/g)) {
  apps[m[1]] ??= cssDecls(`x{${m[2]}}`);
}
const themes = { dark: {}, light };
const hex = rgb => '#' + rgb.map(v => v.toString(16).padStart(2, '0')).join('');
// sRGB source-over, as a browser composites rgba() over an opaque backdrop.
const over = (fg, a, bg) => fg.map((c, i) => Math.round(c * a + bg[i] * (1 - a)));
const mark = (r, min) => `${r.toFixed(2)} ${r >= min ? 'pass' : 'FAIL'}`;

// Surfaces: every --surface-* and --bg-base that resolves to an opaque colour.
// Only --surface-selected depends on the app hue, so it is listed per app.
function surfaces(theme) {
  const map = { ...base, ...apps.seakim, ...themes[theme] };
  const out = [];
  for (const k of Object.keys(map)) {
    if (!/^--(surface-|bg-base)/.test(k)) continue;
    if (k === '--surface-selected') {
      for (const app of Object.keys(apps)) out.push([`${k} (${app})`, toRgb(k, { ...base, ...apps[app], ...themes[theme] })]);
    } else {
      const rgb = toRgb(k, map);
      if (rgb) out.push([k, rgb]);
    }
  }
  return out;
}

const out = [];
const p = s => out.push(s);
p('# Quiet contrast: alpha hairlines, ink primary, app hues');
p('');
p('Generated by `node tool/quiet-contrast.mjs` from `tokens/colors.css`, `tokens/theme-light.css`, `tokens/apps.css` (all generated from `tokens/src/color.tokens.json`). Method: `tool/oklch.mjs` — oklch to sRGB with chroma-reduction gamut mapping, WCAG 2.1 relative luminance, ratio `(L1+0.05)/(L2+0.05)`. Alpha hairlines are composited over the surface in sRGB (source-over) and then measured against that surface. Thresholds: 3:1 non-text (WCAG 1.4.11), 4.5:1 text (WCAG 1.4.3). `--surface-scrim` is a `color-mix()` and is not a backdrop, so it is omitted.');
p('');
p('## What passes');
p('');
p('1. No hairline candidate passes 3:1 anywhere: 8/10/12% ink or white land at 1.17–1.43:1 on every surface, both themes. A hairline at these alphas is decorative only; it cannot be the sole marker of an input or focus boundary.');
p('2. Ink primary passes 4.5:1 on every surface in both themes: light 13.4–18.1:1, dark 9.5–18.0:1; the lowest is `--surface-active` in both.');
p('3. `--text-link` (brand-700 light, brand-300 dark) passes 4.5:1 on every surface for all four hues; the light-theme minimum is bench on `--surface-active` at 5.01:1.');
p('4. `--border-focus` (brand-600 light, brand-400 dark) passes 3:1 on every surface for all four hues; the light-theme minimum is bench on `--surface-active` at 3.26:1, then voyage at 3.44:1.');
p('5. The first alpha that clears 3:1 on the worst surface is 48% ink in light (`--surface-shimmer`) and 41% white in dark (`--surface-active`), about four times the candidate range.');
p('');

const inkOf = { light: base['--stone-900'], dark: '#f5f3f0' };
for (const theme of ['light', 'dark']) {
  const ink = toRgb('ink', { ink: inkOf[theme] });
  const worst = surfaces(theme).map(([n, bg]) => {
    let a = 0.01;
    while (a < 1 && contrast(over(ink, a, bg), bg) < 3) a += 0.01;
    return [n, a];
  }).sort((x, y) => y[1] - x[1])[0];
  p(`## Minimum alpha for 3:1, ${theme}: ${Math.round(worst[1] * 100)}% on \`${worst[0]}\` (the worst surface)`);
  p('');
  p(`## Hairlines, ${theme} — ${inkOf[theme]} at alpha over each surface, 3:1 floor`);
  p('');
  p('| surface | hex | 8% | 10% | 12% |');
  p('|---|---|---|---|---|');
  for (const [name, bg] of surfaces(theme)) {
    const cells = [0.08, 0.10, 0.12].map(a => mark(contrast(over(ink, a, bg), bg), 3));
    p(`| \`${name}\` | ${hex(bg)} | ${cells.join(' | ')} |`);
  }
  p('');
}

p('## Ink primary — `--text-primary` on each surface, 4.5:1 floor');
p('');
p('| theme | surface | hex | text-primary | ratio |');
p('|---|---|---|---|---|');
for (const theme of ['light', 'dark']) {
  const fg = toRgb('--text-primary', { ...base, ...themes[theme] });
  for (const [name, bg] of surfaces(theme)) p(`| ${theme} | \`${name}\` | ${hex(bg)} | ${hex(fg)} | ${mark(contrast(fg, bg), 4.5)} |`);
}
p('');

for (const [app, vars] of Object.entries(apps)) {
  const hue = vars['--brand-500'].match(/([\d.]+)\)/)[1];
  p(`## App \`${app}\` (hue ${hue}) — \`--text-link\` (4.5:1) and \`--border-focus\` (3:1) on each surface`);
  p('');
  p('| theme | surface | hex | text-link | ratio | border-focus | ratio |');
  p('|---|---|---|---|---|---|---|');
  for (const theme of ['light', 'dark']) {
    const map = { ...base, ...vars, ...themes[theme] };
    const link = toRgb('--text-link', map), focus = toRgb('--border-focus', map);
    for (const [name, bg] of surfaces(theme)) {
      if (name.startsWith('--surface-selected') && !name.includes(`(${app})`)) continue;
      p(`| ${theme} | \`${name}\` | ${hex(bg)} | ${hex(link)} | ${mark(contrast(link, bg), 4.5)} | ${hex(focus)} | ${mark(contrast(focus, bg), 3)} |`);
    }
  }
  p('');
}
process.stdout.write(out.join('\n'));
